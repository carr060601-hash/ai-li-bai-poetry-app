export function findFallbackPoem(keyword: string): PoemRecommendation {
  const cleanKey = keyword.trim().toLowerCase();
  
  if (!cleanKey) {
    return CLASSICAL_POEMS[1]; // default to 《月下獨酌》
  }

  // Exact or keyword match
  const matched = CLASSICAL_POEMS.find(poem => {
    return (
      poem.queryKeyword.includes(cleanKey) ||
      cleanKey.includes(poem.queryKeyword) ||
      poem.title.includes(cleanKey) ||
      poem.verses.some(v => v.includes(cleanKey)) ||
      poem.reason.includes(cleanKey) ||
      poem.vernacular.includes(cleanKey) ||
      poem.moodTag.includes(cleanKey)
    );
  });

  if (matched) {
    return {
      ...matched,
      id: `${matched.id}-${Date.now()}`,
      queryKeyword: keyword,
      timestamp: Date.now()
    };
  }

  // Fallback heuristic based on common emotions
  if (cleanKey.includes('月') || cleanKey.includes('夜') || cleanKey.includes('鄉') || cleanKey.includes('家') || cleanKey.includes('念') || cleanKey.includes('母') || cleanKey.includes('親')) {
    return { ...CLASSICAL_POEMS[0], queryKeyword: keyword, timestamp: Date.now() }; // 靜夜思
  }
  if (cleanKey.includes('孤') || cleanKey.includes('獨') || cleanKey.includes('寂') || cleanKey.includes('冷') || cleanKey.includes('影') || cleanKey.includes('一人')) {
    return { ...CLASSICAL_POEMS[1], queryKeyword: keyword, timestamp: Date.now() }; // 月下獨酌
  }
  if (cleanKey.includes('酒') || cleanKey.includes('醉') || cleanKey.includes('愁') || cleanKey.includes('窮') || cleanKey.includes('錢') || cleanKey.includes('人生') || cleanKey.includes('悲')) {
    return { ...CLASSICAL_POEMS[2], queryKeyword: keyword, timestamp: Date.now() }; // 將進酒
  }
  if (cleanKey.includes('靜') || cleanKey.includes('空') || cleanKey.includes('山') || cleanKey.includes('坐') || cleanKey.includes('鳥') || cleanKey.includes('累')) {
    return { ...CLASSICAL_POEMS[3], queryKeyword: keyword, timestamp: Date.now() }; // 獨坐敬亭山
  }
  if (cleanKey.includes('難') || cleanKey.includes('迷') || cleanKey.includes('茫') || cleanKey.includes('困') || cleanKey.includes('折') || cleanKey.includes('阻') || cleanKey.includes('路')) {
    return { ...CLASSICAL_POEMS[4], queryKeyword: keyword, timestamp: Date.now() }; // 行路難
  }
  if (cleanKey.includes('友') || cleanKey.includes('朋') || cleanKey.includes('伴') || cleanKey.includes('謝') || cleanKey.includes('歌')) {
    return { ...CLASSICAL_POEMS[5], queryKeyword: keyword, timestamp: Date.now() }; // 贈汪倫
  }
  if (cleanKey.includes('順') || cleanKey.includes('走') || cleanKey.includes('輕') || cleanKey.includes('快') || cleanKey.includes('舟') || cleanKey.includes('脫') || cleanKey.includes('釋')) {
    return { ...CLASSICAL_POEMS[6], queryKeyword: keyword, timestamp: Date.now() }; // 早發白帝城
  }
  if (cleanKey.includes('煩') || cleanKey.includes('擾') || cleanKey.includes('鬱') || cleanKey.includes('悶') || cleanKey.includes('斷') || cleanKey.includes('刀')) {
    return { ...CLASSICAL_POEMS[7], queryKeyword: keyword, timestamp: Date.now() }; // 宣州謝朓樓
  }

  // Random classic pick
  const randomIndex = Math.floor(Math.random() * CLASSICAL_POEMS.length);
  const picked = CLASSICAL_POEMS[randomIndex];
  return {
    ...picked,
    id: `${picked.id}-${Date.now()}`,
    queryKeyword: keyword,
    timestamp: Date.now()
  };
}
